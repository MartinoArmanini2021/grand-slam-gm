// ── Generate the Cincinnati player_stats seed (id, ranking, price, tier) ─────────────────────────
// save_entry validates the TIER QUOTA off public.player_stats.tier and the BUDGET off .price, so a
// row with only `ranking` is not enough: a NULL tier is excluded by the `count(*) filter (where
// ps.tier = …)` quota check (so a legal 2/3/5 squad reads as 2/3/4 and cannot lock) and a NULL price
// is skipped by sum() (so the budget check under-counts). Every drafted player needs all four.
//
//   node scripts/gen-cincinnati-seed.mjs          # writes supabase/seed_cincinnati_player_stats.sql
//   node scripts/gen-cincinnati-seed.mjs --check  # verify only; non-zero exit if it would change
//
// Pricing is replicated from src/data/players.ts (priceBreakdown) and SELF-CHECKED against the
// Montréal block already in save_entry_rpc.sql: every player common to both events must come out at
// the identical price/tier, or the two seeds would disagree and the parity test would fail.

import { readFileSync, writeFileSync } from 'node:fs';

const field = JSON.parse(readFileSync(new URL('../src/data/cincinnati2026Field.json', import.meta.url), 'utf8'));
const rpcSql = readFileSync(new URL('../supabase/save_entry_rpc.sql', import.meta.url), 'utf8');
const OUT = new URL('../supabase/seed_cincinnati_player_stats.sql', import.meta.url);

// getTier — src/data/tiers.ts
const tierOf = (r) => (r <= 10 ? 'Platinum' : r <= 25 ? 'Gold' : 'Silver');

// priceBreakdown — src/data/players.ts. Cincinnati is a HARD court, so the surface term reads
// surface.hard (TOURNAMENT.surface). Field values already come from the pool overlay, so this
// matches what the client renders.
function priceOf(ranking, ytd, surfHard) {
  const rawBase = 55 * Math.pow(Math.max(1, ranking), -0.46);
  const played = ytd ? ytd.wins + ytd.losses : 0;
  const winRate = played >= 8 ? ytd.wins / played : null;
  const formMult = 1 + (winRate != null ? (winRate - 0.5) * 0.9 : 0) + Math.min(0.12, (ytd?.titles ?? 0) * 0.03);
  const surfMult = 1 + (surfHard != null ? (surfHard / 100 - 0.5) * 0.5 : 0);
  return Math.max(4, Math.min(50, Math.round(rawBase * formMult * surfMult)));
}

const rows = field.map(p => ({
  id: p.id,
  ranking: p.ranking,
  price: priceOf(p.ranking, p.ytd, p.surface?.hard),
  tier: tierOf(p.ranking),
})).sort((a, b) => a.ranking - b.ranking);

// ── SELF-CHECK: shared players must match the Montréal seed exactly ──────────────────────────────
const montreal = new Map(
  [...rpcSql.matchAll(/\(\s*'([a-z0-9]+)'\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*'(\w+)'\s*\)/g)]
    .map(m => [m[1], { ranking: +m[2], price: +m[3], tier: m[4] }]),
);
const clashes = rows.filter(r => {
  const m = montreal.get(r.id);
  return m && (m.ranking !== r.ranking || m.price !== r.price || m.tier !== r.tier);
});
const shared = rows.filter(r => montreal.has(r.id)).length;
console.log(`  cincinnati field: ${rows.length}`);
console.log(`  shared with the Montréal seed: ${shared}   mismatches: ${clashes.length}`);
for (const c of clashes) {
  const m = montreal.get(c.id);
  console.log(`    ✗ ${c.id}: montreal rank ${m.ranking} $${m.price} ${m.tier} — cincinnati rank ${c.ranking} $${c.price} ${c.tier}`);
}
if (clashes.length) {
  console.error('\n  ✗ the two seeds disagree — resolve before shipping (they share one player_stats table).\n');
  process.exitCode = 1;
} else {
  const body = rows.map(r => `  ('${r.id}', ${r.ranking}, ${r.price}, '${r.tier}')`).join(',\n');
  const sql = `-- ── Cincinnati Open 2026 — player_stats seed for server-side validation + scoring ────────────────
-- WHY ALL FOUR COLUMNS: save_entry validates the TIER QUOTA off player_stats.tier and the BUDGET off
-- .price, and recompute-score reads .ranking for the upset multiplier. A row carrying only \`ranking\`
-- leaves tier/price NULL — the quota check then reads a legal 2/3/5 squad as 2/3/4 (so it can never
-- be locked) and sum(price) silently under-counts the budget. Every drafted player needs all four.
--
-- Generated by scripts/gen-cincinnati-seed.mjs from src/data/cincinnati2026Field.json (built from the
-- published draw and reconciled against Wikipedia: 0 missing, 0 phantom). ${rows.length} players.
--
-- SAFE TO RUN ANY TIME, INCLUDING WHILE MONTRÉAL IS STILL SCORED: the generator verifies that every
-- player common to both events (${shared} of them) carries an IDENTICAL rank, price and tier to the
-- Montréal block in save_entry_rpc.sql — so this only ADDS the ${rows.length - shared} players new to
-- Cincinnati and cannot retroactively alter a Montréal score. The upsert keeps it re-runnable.
--
-- Apply in the Supabase SQL editor. Order does not matter relative to save_entry_rpc.sql.

insert into public.player_stats (id, ranking, price, tier) values
${body}
on conflict (id) do update set ranking = excluded.ranking, price = excluded.price, tier = excluded.tier;

-- Verify: every Cincinnati entrant now has a complete row (expect ${rows.length}, and 0 incomplete).
-- select count(*) as complete from public.player_stats where price is not null and tier is not null;
`;
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8');
    if (current.trim() !== sql.trim()) { console.error('\n  ✗ seed file is out of date — re-run without --check\n'); process.exitCode = 1; }
    else console.log('\n  ✓ seed file is up to date\n');
  } else {
    writeFileSync(OUT, sql);
    console.log(`\n  ✓ wrote ${rows.length} rows → supabase/seed_cincinnati_player_stats.sql`);
    console.log(`    (${rows.length - shared} new to Cincinnati, ${shared} identical to Montréal)\n`);
  }
}
